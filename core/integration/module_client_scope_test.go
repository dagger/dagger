const moduleClientScopeConfig = `[modules.go-sdk]
source = ".dagger/modules/go-sdk"

[modules.python-sdk]
source = ".dagger/modules/python-sdk"
settings.clientRootMarker = "pyproject.toml"
settings.clientOutputDir = "python-clients"

[modules.target]
source = "target"

[sdks.go]
module = "go-sdk"

[sdks.python]
module = "python-sdk"
`

func moduleClientScopeTestBase(ctx context.Context, t *testctx.T) *dagger.Container {
	t.Helper()
	c := connect(ctx, t)
	sdkPath, err := filepath.Abs("testdata/sdks/module-max-lifecycle")
	require.NoError(t, err)
	sdk := c.Host().Directory(sdkPath)
	return goGitBase(t, c).
		WithEnvVariable("_EXPERIMENTAL_DAGGER_CLI_BIN", testCLIBinPath).
		With(nonNestedDevEngine(c)).
		WithDirectory("/work/.dagger/modules/go-sdk", sdk).
		WithDirectory("/work/.dagger/modules/python-sdk", sdk).
		WithNewFile("/work/dagger.toml", moduleClientScopeConfig).
		WithNewFile("/work/target/dagger-module.toml", `name = "target"
engineVersion = "latest"
[runtime]
source = "dang"
`).
		WithNewFile("/work/target/main.dang", `type Target { hello: String! { "hello" } }`).
		WithNewFile("/work/app/sub/.keep", "").
		WithWorkdir("/work/app/sub")
}

func readModuleClientConfig(ctx context.Context, t *testctx.T, ctr *dagger.Container) *workspacecfg.Config {
	t.Helper()
	contents, err := ctr.File("/work/dagger.toml").Contents(ctx)
	require.NoError(t, err)
	cfg, err := workspacecfg.ParseConfig([]byte(contents))
	require.NoError(t, err)
	return cfg
}

func (GeneratorsSuite) TestModuleClientAddScopeSelection(ctx context.Context, t *testctx.T) {
	base := moduleClientScopeTestBase(ctx, t)
	for _, test := range []struct {
		name    string
		markers []string
		config  string
		sdk     string
		wantSDK string
		wantDir string
	}{
		{name: "one detected SDK", markers: []string{"app/go.mod"}, wantSDK: "go", wantDir: "app"},
		{name: "deeper Python", markers: []string{"go.mod", "app/pyproject.toml"}, wantSDK: "python", wantDir: "app"},
		{name: "deeper Go", markers: []string{"pyproject.toml", "app/go.mod"}, wantSDK: "go", wantDir: "app"},
		{name: "deeper recorded scope", markers: []string{"go.mod", "app/pyproject.toml"},
			config: "\n[sdks.go.scopes.\"app/sub\"]\n", wantSDK: "go", wantDir: "app/sub"},
		{name: "deeper detected scope", markers: []string{"app/go.mod"},
			config: "\n[sdks.go.scopes.\".\"]\n", wantSDK: "go", wantDir: "app"},
		{name: "recorded scope without detection", config: "\n[sdks.go.scopes.app]\n", wantSDK: "go", wantDir: "app"},
		{name: "deeper scope resolves root tie", markers: []string{"go.mod", "pyproject.toml"},
			config: "\n[sdks.go.scopes.app]\n", wantSDK: "go", wantDir: "app"},
		{name: "explicit SDK selects shallower scope", markers: []string{"go.mod", "app/pyproject.toml"},
			sdk: "go", wantSDK: "go", wantDir: "."},
		{name: "explicit SDK resolves tie", markers: []string{"app/go.mod", "app/pyproject.toml"},
			sdk: "python", wantSDK: "python", wantDir: "app"},
		{name: "duplicate in another SDK", markers: []string{"app/go.mod"},
			config: "\n[sdks.python.scopes.\".\"]\nclients = [\"target\"]\n", wantSDK: "go", wantDir: "app"},
		{name: "duplicate in another scope", markers: []string{"app/go.mod"},
			config: "\n[sdks.go.scopes.\".\"]\nclients = [\"target\"]\n", wantSDK: "go", wantDir: "app"},
	} {
		t.Run(test.name, func(ctx context.Context, t *testctx.T) {
			ctr := base.WithNewFile("/work/dagger.toml", moduleClientScopeConfig+test.config)
			for _, marker := range test.markers {
				ctr = ctr.WithNewFile("/work/"+marker, "")
			}
			args := []string{"module", "client", "add", "target", "-y"}
			if test.sdk != "" {
				args = append(args, "--sdk="+test.sdk)
			}
			added := ctr.With(daggerNonNestedExec(args...))
			out, err := added.CombinedOutput(ctx)
			require.NoError(t, err, out)
			expected := readModuleClientConfig(ctx, t, ctr)
			entry := expected.SDKs[test.wantSDK]
			if entry.Scopes == nil {
				entry.Scopes = map[string]workspacecfg.SDKScope{}
			}
			scope := entry.Scopes[test.wantDir]
			scope.Clients = append(scope.Clients, "target")
			entry.Scopes[test.wantDir] = scope
			expected.SDKs[test.wantSDK] = entry
			require.Equal(t, expected, readModuleClientConfig(ctx, t, added))
			outputDir := "internal/dagger/clients"
			if test.wantSDK == "python" {
				outputDir = "python-clients"
			}
			contents, err := added.File(filepath.Join("/work", test.wantDir, outputDir, "target.gen.go")).Contents(ctx)
			require.NoError(t, err)
			require.Contains(t, contents, "Code generated by module-max-lifecycle")
		})
	}

	for _, test := range []struct {
		name    string
		markers []string
		config  string
		args    []string
		wantErr string
	}{
		{name: "no scope", wantErr: "client generation is not available"},
		{name: "no installed SDK", config: "# no SDKs\n", wantErr: "no SDK modules are installed"},
		{name: "unknown SDK", args: []string{"--sdk=missing"}, wantErr: `"missing" is not installed as an SDK`},
		{name: "explicit SDK has no scope", markers: []string{"app/go.mod"}, args: []string{"--sdk=python"},
			wantErr: "client generation is not available"},
		{name: "deepest tie", markers: []string{"app/go.mod", "app/pyproject.toml"},
			wantErr: `SDK "go" at "app", SDK "python" at "app"; select one with --sdk`},
		{name: "duplicate", markers: []string{"app/go.mod"},
			config:  moduleClientScopeConfig + "\n[sdks.go.scopes.app]\nclients = [\"target\"]\n",
			wantErr: `client target "target" already exists in SDK "go" scope "app"`},
		{name: "SDK settings flag", args: []string{"--starter=empty"}, wantErr: "unknown flag: --starter"},
		{name: "old SDK argument", args: []string{"go"}, wantErr: "accepts 1 arg(s), received 2"},
	} {
		t.Run(test.name, func(ctx context.Context, t *testctx.T) {
			ctr := base
			if test.config != "" {
				ctr = ctr.WithNewFile("/work/dagger.toml", test.config)
			}
			for _, marker := range test.markers {
				ctr = ctr.WithNewFile("/work/"+marker, "")
			}
			args := append([]string{"module", "client", "add", "target", "-y"}, test.args...)
			failed := ctr.With(daggerNonNestedExecFail(args...))
			out, err := failed.CombinedOutput(ctx)
			require.NoError(t, err, out)
			require.Contains(t, out, test.wantErr)
			before, err := ctr.Directory("/work").Digest(ctx)
			require.NoError(t, err)
			after, err := failed.Directory("/work").Digest(ctx)
			require.NoError(t, err)
			require.Equal(t, before, after)
		})
	}

	t.Run("SDK detection failure", func(ctx context.Context, t *testctx.T) {
		source, err := base.File("/work/.dagger/modules/python-sdk/main.dang").Contents(ctx)
		require.NoError(t, err)
		source = strings.Replace(source, "ws.findUp(clientRootMarker)", `ws.findUp(ws.file("missing-marker").contents)`, 1)
		ctr := base.WithNewFile("/work/.dagger/modules/python-sdk/main.dang", source).
			WithNewFile("/work/app/go.mod", "")
		failed := ctr.With(daggerNonNestedExecFail("module", "client", "add", "target", "-y"))
		out, err := failed.CombinedOutput(ctx)
		require.NoError(t, err, out)
		require.Contains(t, out, "stat missing-marker: no such file or directory")
		require.Equal(t, readModuleClientConfig(ctx, t, ctr), readModuleClientConfig(ctx, t, failed))
		selected := ctr.With(daggerNonNestedExec("module", "client", "add", "target", "--sdk=go", "-y"))
		out, err = selected.CombinedOutput(ctx)
		require.NoError(t, err, out)
		require.Equal(t, []string{"target"}, readModuleClientConfig(ctx, t, selected).SDKs["go"].Scopes["app"].Clients)
	})

	t.Run("generation failure preserves records", func(ctx context.Context, t *testctx.T) {
		source, err := base.File("/work/.dagger/modules/go-sdk/main.dang").Contents(ctx)
		require.NoError(t, err)
		source = strings.Replace(source, "clients.reduce(clean)", `clients.reduce(clean.withNewFile("failure", ws.file("missing-generation-file").contents))`, 1)
		ctr := base.WithNewFile("/work/.dagger/modules/go-sdk/main.dang", source).
			WithNewFile("/work/go.mod", "")
		failed := ctr.With(daggerNonNestedExecFail("module", "client", "add", "target", "-y"))
		out, err := failed.CombinedOutput(ctx)
		require.NoError(t, err, out)
		require.Contains(t, out, "missing-generation-file")
		require.Equal(t, readModuleClientConfig(ctx, t, ctr), readModuleClientConfig(ctx, t, failed))
	})
}

func (GeneratorsSuite) TestModuleClientListRemoval(ctx context.Context, t *testctx.T) {
	const records = `
[sdks.go.scopes."."]
clients = ["target"]
[sdks.go.scopes.app]
clients = ["target"]
[sdks.python.scopes.app]
clients = ["target"]
[sdks.python.scopes.other]
clients = ["target"]
[sdks.go.scopes."app/other"]
clients = ["github.com/example/module/subdir@v1.2.3"]
`
	base := moduleClientScopeTestBase(ctx, t).
		WithNewFile("/work/dagger.toml", moduleClientScopeConfig+records).
		WithNewFile("/work/other/.keep", "").
		WithNewFile("/work/app/other/.keep", "")

	listed, err := base.With(daggerNonNestedExec("module", "client", "list")).Stdout(ctx)
	require.NoError(t, err)
	rows := strings.Split(strings.TrimSpace(listed), "\n")
	require.Len(t, rows, 4)
	require.NotContains(t, listed, "other")
	all, err := base.With(daggerNonNestedExec("module", "client", "list", "--all")).Stdout(ctx)
	require.NoError(t, err)
	rows = strings.Split(strings.TrimSpace(all), "\n")
	require.Len(t, rows, 6)
	require.Contains(t, all, "github.com/example/module/subdir@v1.2.3")
	for _, row := range rows[1:] {
		fields := strings.Fields(row)
		require.Len(t, fields, 3, row)
		scopePath, sdk, target := fields[0], fields[1], fields[2]
		t.Run(fmt.Sprintf("remove %s at %s", sdk, scopePath), func(ctx context.Context, t *testctx.T) {
			removed := base.WithWorkdir(filepath.Join("/work", scopePath)).
				With(daggerNonNestedExec("module", "client", "rm", target, "--sdk="+sdk, "-y"))
			out, err := removed.CombinedOutput(ctx)
			require.NoError(t, err, out)
			expected := readModuleClientConfig(ctx, t, base)
			entry := expected.SDKs[sdk]
			delete(entry.Scopes, scopePath)
			expected.SDKs[sdk] = entry
			require.Equal(t, expected, readModuleClientConfig(ctx, t, removed))
		})
	}

	for _, args := range [][]string{
		{"module", "client", "rm", "target", "-y"},
		{"module", "client", "rm", "target", "--sdk=missing", "-y"},
		{"module", "client", "rm", "./target", "-y"},
	} {
		failed := base.With(daggerNonNestedExecFail(args...))
		out, err := failed.CombinedOutput(ctx)
		require.NoError(t, err, out)
		require.Equal(t, readModuleClientConfig(ctx, t, base), readModuleClientConfig(ctx, t, failed))
	}
	filtered, err := base.With(daggerNonNestedExec("module", "client", "list", "--all", "--sdk=python")).Stdout(ctx)
	require.NoError(t, err)
	require.Len(t, strings.Split(strings.TrimSpace(filtered), "\n"), 3)
	for _, row := range strings.Split(strings.TrimSpace(filtered), "\n")[1:] {
		require.Equal(t, "python", strings.Fields(row)[1])
	}

	// A new project marker must not redirect removal away from its recorded scope.
	unique := base.WithNewFile("/work/dagger.toml", moduleClientScopeConfig+"\n[sdks.go.scopes.app]\nclients = [\"target\"]\n").
		WithNewFile("/work/app/sub/go.mod", "").
		With(daggerNonNestedExec("module", "client", "rm", "target", "-y"))
	out, err := unique.CombinedOutput(ctx)
	require.NoError(t, err, out)
	require.Empty(t, readModuleClientConfig(ctx, t, unique).SDKs["go"].Scopes)

	deepest := base.WithNewFile("/work/dagger.toml", moduleClientScopeConfig+`
[sdks.go.scopes."."]
clients = ["target"]
[sdks.python.scopes.app]
clients = ["target"]
`).With(daggerNonNestedExec("module", "client", "rm", "target", "-y"))
	out, err = deepest.CombinedOutput(ctx)
	require.NoError(t, err, out)
	cfg := readModuleClientConfig(ctx, t, deepest)
	require.Empty(t, cfg.SDKs["python"].Scopes)
	require.Equal(t, []string{"target"}, cfg.SDKs["go"].Scopes["."].Clients)
}

func (GeneratorsSuite) TestModuleClientAPISettings(ctx context.Context, t *testctx.T) {
	base := moduleClientScopeTestBase(ctx, t).WithNewFile("/work/app/go.mod", "")
	query := `query { currentWorkspace { withClient(module: "target", settings: "{\"clientOutputDir\":\"custom-clients\"}") { configRead } } }`
	failed := base.WithNewFile("/query.graphql", query).
		With(daggerNonNestedExecFail("api", "query", "--doc=/query.graphql"))
	out, err := failed.CombinedOutput(ctx)
	require.NoError(t, err, out)
	require.Contains(t, out, "SDK name is required when client settings are supplied")

	query = strings.Replace(query, `module: "target",`, `module: "target", sdk: "go",`, 1)
	out, err = base.WithNewFile("/query.graphql", query).
		With(daggerNonNestedExec("api", "query", "--doc=/query.graphql")).Stdout(ctx)
	require.NoError(t, err, out)
	require.Contains(t, out, "custom-clients")
	require.Contains(t, out, "clientOutputDir")
}
