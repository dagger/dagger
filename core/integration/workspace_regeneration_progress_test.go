package core

import (
	"context"
	"path/filepath"

	"dagger.io/dagger"
	"github.com/dagger/testctx"
	"github.com/stretchr/testify/require"
)

func updateProgressFixture(t *testctx.T, c *dagger.Client) *dagger.Container {
	sdkPath, err := filepath.Abs("testdata/sdks/module-max-lifecycle")
	require.NoError(t, err)
	return goGitBase(t, c).
		WithEnvVariable("_EXPERIMENTAL_DAGGER_CLI_BIN", testCLIBinPath).
		With(nonNestedDevEngine(c)).
		WithDirectory(".dagger/modules/sdk", c.Host().Directory(sdkPath)).
		WithNewFile("dagger.toml", `[modules.api]
source = "./api"
[modules.go-sdk]
source = ".dagger/modules/sdk"
[sdks.go]
module = "go-sdk"
[sdks.go.scopes.web]
clients = ["./api"]
`).
		WithNewFile("api/dagger-module.toml", "name = \"api\"\nengineVersion = \"latest\"\n[runtime]\nsource = \"dang\"\n").
		WithNewFile("api/main.dang", "type Api { hello: String! { \"hello\" } }\n").
		WithNewFile("web/go.mod", "module web\n\ngo 1.25\n")
}

func (GeneratorsSuite) TestModuleUpdateRegenerationProgress(ctx context.Context, t *testctx.T) {
	c := connect(ctx, t)
	base := updateProgressFixture(t, c)
	updated := base.With(daggerNonNestedExec("module", "update", "api"))
	out, err := updated.CombinedOutput(ctx)
	require.NoError(t, err, out)
	contents, err := updated.File("web/internal/dagger/clients/api.gen.go").Contents(ctx)
	require.NoError(t, err)
	require.Contains(t, contents, "Code generated by module-max-lifecycle")

	failed := base.WithNewFile(".dagger/modules/sdk/main.dang", "intentionally invalid").
		With(daggerNonNestedExecFail("module", "update", "api"))
	out, err = failed.CombinedOutput(ctx)
	require.NoError(t, err, out)
	require.Contains(t, out, "re-generate")
	require.Contains(t, out, "./web")
	require.Contains(t, out, "update: api")
}

