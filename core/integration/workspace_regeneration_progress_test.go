func (GeneratorsSuite) TestWorkspaceUpdateRegenerationProgress(ctx context.Context, t *testctx.T) {
	c := connect(ctx, t)
	base := updateProgressFixture(t, c)
	updated := base.With(daggerNonNestedExec("workspace", "update"))
	out, err := updated.CombinedOutput(ctx)
	require.NoError(t, err, out)
	contents, err := updated.File("web/internal/dagger/clients/api.gen.go").Contents(ctx)
	require.NoError(t, err)
	require.Contains(t, contents, "Code generated by module-max-lifecycle")
	failed := base.WithNewFile(".dagger/modules/sdk/main.dang", "intentionally invalid").
		With(daggerNonNestedExecFail("workspace", "update"))
	out, err = failed.CombinedOutput(ctx)
	require.NoError(t, err, out)
	require.Contains(t, out, "re-generate")
	require.Contains(t, out, "./web")
	require.Contains(t, out, "update workspace")
	// --no-generate must not load the broken SDK or create a regeneration group.
	out, err = base.WithNewFile(".dagger/modules/sdk/main.dang", "intentionally invalid").
		With(daggerNonNestedExec("workspace", "update", "--no-generate")).CombinedOutput(ctx)
	require.NoError(t, err, out)
	require.NotContains(t, out, "re-generate")
}
