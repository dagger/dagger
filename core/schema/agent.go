func (s agentSchema) waitFor(ctx context.Context, parent dagql.ObjectResult[*core.Agent], args struct {
	State core.AgentState `default:"IDLE"`
}) (res dagql.Result[core.AgentID], _ error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return res, err
	}
	// Create the entry lazily (without starting the loop) so waiting on a
	// never-started agent blocks on future transitions instead of erroring.
	rt, err := agents.GetOrCreate(ctx, parent)
	if err != nil {
		return res, err
	}
	if err := rt.WaitFor(ctx, args.State); err != nil {
		return res, err
	}
	return agentSelfID(ctx, parent)
}

func (s agentSchema) waitSettled(ctx context.Context, parent dagql.ObjectResult[*core.Agent], _ struct{}) (res dagql.Result[core.AgentID], _ error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return res, err
	}
	// Lazy entry, like waitFor: a never-started agent projects IDLE, which
	// is settled, so this returns immediately rather than erroring.
	rt, err := agents.GetOrCreate(ctx, parent)
	if err != nil {
		return res, err
	}
	if _, err := rt.WaitSettled(ctx); err != nil {
		return res, err
	}
	return agentSelfID(ctx, parent)
}

func (s agentSchema) stop(ctx context.Context, parent dagql.ObjectResult[*core.Agent], args struct {
	Kill bool `default:"false"`
}) (res dagql.Result[core.AgentID], _ error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return res, err
	}
	// Stopping a never-started agent still creates its entry, transitioned
	// straight to a dormant tombstone. Stop remains idempotent; send or resume
	// may relaunch the entry later.
	rt, err := agents.GetOrCreate(ctx, parent)
	if err != nil {
		return res, err
	}
	// Somebody asked for this stop, which is what distinguishes it from the
	// one session teardown performs on every surviving entry — the terminal
	// telemetry record carries the difference (core.AgentStopReason).
	if err := rt.Stop(ctx, args.Kill, nil, core.AgentStopExplicit); err != nil {
		return res, err
	}
	return agentSelfID(ctx, parent)
}

// reseed swaps the receiver instance's committed conversation for the one
// given as an argument. Argument-shaped deliberately, unlike rehydrate: a
// runtime verb's receiver NAMES an instance and never redefines one — the
// invariant that makes telemetry-rebuilt handles safe to hold (design §10.2:
// the seed is read only at entry creation). Creation verbs (spawn, rehydrate)
// read the receiver as the seed because creation is the one moment a chain
// defines an entry; everything an already-created entry is told to do arrives
// as an argument.
func (s agentSchema) reseed(ctx context.Context, parent dagql.ObjectResult[*core.Agent], args struct {
	Conversation core.LLMID
}) (res dagql.Result[core.AgentID], _ error) {
	srv, err := core.CurrentDagqlServer(ctx)
	if err != nil {
		return res, err
	}
	conversation, err := args.Conversation.Load(ctx, srv)
	if err != nil {
		return res, err
	}
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return res, err
	}
	if err := agents.Reseed(ctx, parent, conversation); err != nil {
		return res, err
	}
	return agentSelfID(ctx, parent)
}

// rehydrate adopts the receiver's conversation as a restored instance's
// committed history (hack/designs/resume-from-trace.md §4.1). Like the other
// imperative verbs it is ID-returning: the ID is the pinned agent chain, so a
// client re-hydrates the handle from it and addresses the entry it just
// created — which is exactly what a restoring client then attaches to.
func (s agentSchema) rehydrate(ctx context.Context, parent dagql.ObjectResult[*core.Agent], args struct {
	State core.AgentState `default:"IDLE"`
	Error string          `default:""`
}) (res dagql.Result[core.AgentID], _ error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return res, err
	}
	if _, err := agents.Rehydrate(ctx, parent, args.State, args.Error); err != nil {
		return res, err
	}
	return agentSelfID(ctx, parent)
}
