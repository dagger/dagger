package schema

import (
	"context"
	"fmt"

	"github.com/dagger/dagger/core"
	"github.com/dagger/dagger/dagql"
)

// agentSchema installs the Agent type: the async evaluation-loop entity of
// hack/designs/async-agents.md. The Agent value itself is constructed by
// LLM.asAgent (core/schema/llm.go); this file installs its lifecycle fields,
// all of which operate on the session-scoped runtime registry
// (core.AgentRuntimes) rather than on the value.
type agentSchema struct{}

var _ SchemaResolvers = &agentSchema{}

func (s agentSchema) Install(srv *dagql.Server) {
	dagql.Fields[*core.Agent]{
		dagql.Func("name", s.name).
			Doc(`Display label and identity discriminator — not a session-wide address.`),

		dagql.NodeFunc("state", s.state).
			DoNotCache("Projects live runtime state.").
			Doc(`Computed lifecycle state; never stored.`,
				`An agent that was never started reports IDLE: its mailbox is empty and no turn is open.`),

		dagql.NodeFunc("snapshot", s.snapshot).
			DoNotCache("Reflects the loop's last committed step, which advances as the agent runs.").
			Doc(`The conversation as of the last committed step: immutable, branchable, persistable.`,
				`The seed conversation if the agent never stepped.`,
				`Branching from it does not affect the agent.`),

		dagql.NodeFunc("start", s.start).
			DoNotCache("Imperatively mutates runtime state.").
			Doc(`Start the agent's evaluation loop. No-op if it is already running.`,
				`The loop runs detached from the calling request: it steps the conversation while input is pending, then idles awaiting further lifecycle operations.`),

		dagql.NodeFunc("send", s.send).
			DoNotCache("Every send enqueues a distinct message into live runtime state.").
			Doc(`Enqueue a message, on the record: it is consumed at a step boundary, appends to the agent's history, and steers the running turn or opens a new one.`,
				`Never blocks, never drops; concurrent sends queue in order.`,
				`The returned message ID is pinned through the message lookup field, so the handle it loads is re-addressable from any request in the session: cancel an await and re-await freely.`,
				`Sending to a never-started agent starts it (signal-with-start). Sending to a paused or failed agent enqueues with QUEUED delivery, to be drained by a resume. Sending to a stopped agent fails: nothing would ever consume the message.`).
			Args(
				dagql.Arg("message").Doc(`The message text, appended to the agent's history as a prompt when a turn consumes it.`),
			),

		// message is deliberately cached (no DoNotCache): the message ID
		// argument pins the lookup to one immutable record — delivery
		// evidence is computed once at enqueue and records are never
		// deleted — so the same chain always denotes the same handle. And
		// the chain is per-session by construction (every Agent descends
		// from Query.llm's PerSessionInput), so the cached handle can never
		// leak across sessions. Caching is also what makes send's re-exec
		// pinning cheap: re-loading a pinned ID replays …asAgent!message(…)
		// and lands on the same cached instance.
		dagql.NodeFunc("message", s.message).
			Doc(`Look up a previously sent message by its message ID, returning its handle.`,
				`This is the lookup send pins its result's identity through: the returned handle's ID is an honest, replayable chain, addressable from any request in the session (the cancel-and-re-await contract).`,
				`Fails if the agent has no runtime entry in this session, or no record of the given ID.`).
			Args(
				dagql.Arg("id").Doc(`The message ID, as generated by the send that enqueued the message.`),
			),

		dagql.NodeFunc("interrupt", s.interrupt).
			DoNotCache("Imperatively mutates runtime state.").
			Doc(`Preempt the in-flight step, keeping all completed steps, and pause.`,
				`The interrupted turn stays open: messages it consumed remain pending, and resume continues the turn from the last committed step. To redirect, follow with send — steering and interrupting are separate verbs.`,
				`On an idle, never-started, or failed agent this is equivalent to pause. Interrupting a stopped agent fails.`),

		dagql.NodeFunc("pause", s.pause).
			DoNotCache("Imperatively mutates runtime state.").
			Doc(`Stop draining the mailbox once the in-flight step completes.`,
				`Pause takes priority over pending work: a mid-turn pause suspends the turn, which resume continues. Messages sent while paused enqueue with QUEUED delivery until a resume.`,
				`Pausing a never-started agent leaves it paused for its eventual start; pausing a failed agent is allowed (resume decides the retry); pausing a stopped agent fails.`),

		dagql.NodeFunc("resume", s.resume).
			DoNotCache("Imperatively mutates runtime state.").
			Doc(`Resume draining the mailbox: a suspended turn continues from the last committed step, and queued messages drain.`,
				`Resuming a FAILED agent retries: the loop relaunches from the last committed snapshot, whose still-pending input is stepped again.`,
				`No-op on a running or idle agent; resuming a stopped agent fails.`),

		dagql.NodeFunc("waitFor", s.waitFor).
			DoNotCache("Blocks on live runtime state.").
			Doc(`Block until the agent reaches the given state, returning immediately if it is already there.`,
				`Fails if the state becomes unreachable: STOPPED is the only terminal state — waiting on a FAILED agent for another state blocks, since a resume may retry the loop.`).
			Args(
				dagql.Arg("state").Doc(`The lifecycle state to wait for.`),
			),

		dagql.NodeFunc("stop", s.stop).
			DoNotCache("Imperatively mutates runtime state.").
			Doc(`Release the agent's runtime. The tombstone (state, snapshot) stays readable for the rest of the session.`).
			Args(
				dagql.Arg("kill").Doc(`Cancel the loop immediately instead of letting an in-flight step finish. Either way the completed steps are preserved in the snapshot.`),
			),
	}.Install(srv)

	dagql.Fields[*core.AgentMessage]{
		dagql.Func("delivery", s.messageDelivery).
			Doc(`How the message landed: opened a new turn (STARTED), was absorbed into the running turn at a step boundary (STEERED), or queued behind it (QUEUED).`,
				`Computed once, at enqueue time.`),

		dagql.Func("await", s.messageAwait).
			DoNotCache("Blocks on live runtime state.").
			Doc(`Block until the turn that consumed this message ends, and return that turn's reply.`,
				`Idempotent: cancel and re-await freely; concurrent waiters share the result.`,
				`Fails if the agent stops before the message resolves. On a failed agent it projects the failure — but the message stays pending, so after a resume consumes it, a re-await returns the real reply.`),
	}.Install(srv)

	core.AgentStates.Install(srv)
	core.AgentMessageDeliveries.Install(srv)
}

func (s agentSchema) name(ctx context.Context, agent *core.Agent, _ struct{}) (string, error) {
	return agent.Name, nil
}

func agentRuntimes(ctx context.Context) (*core.AgentRuntimes, error) {
	query, err := core.CurrentQuery(ctx)
	if err != nil {
		return nil, err
	}
	return query.Agents(ctx)
}

// agentSelfID returns the parent agent's own ID as the field's result — the
// sync-style contract of the imperative verbs (like Service.start/stop): they
// return ID! with @expectedType rather than the object, so lazy clients force
// the verb at the call site and re-hydrate the handle from the ID instead of
// re-evaluating a DoNotCache chain (which would re-run the side effect).
func agentSelfID(ctx context.Context, parent dagql.ObjectResult[*core.Agent]) (res dagql.Result[core.AgentID], _ error) {
	parentID, err := parent.ID()
	if err != nil {
		return res, fmt.Errorf("agent ID: %w", err)
	}
	return dagql.NewResultForCurrentCall(ctx, dagql.NewID[*core.Agent](parentID))
}

func (s agentSchema) state(ctx context.Context, parent dagql.ObjectResult[*core.Agent], _ struct{}) (core.AgentState, error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return "", err
	}
	rt, found, err := agents.Get(ctx, parent)
	if err != nil {
		return "", err
	}
	if !found {
		// Never started: no runtime entry exists (reads never create one),
		// and the projected state of that absence is IDLE — mailbox empty,
		// no turn open. The entry is created lazily by start/waitFor/stop.
		return core.AgentStateIdle, nil
	}
	return rt.State(), nil
}

func (s agentSchema) snapshot(ctx context.Context, parent dagql.ObjectResult[*core.Agent], _ struct{}) (res dagql.ObjectResult[*core.LLM], _ error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return res, err
	}
	rt, found, err := agents.Get(ctx, parent)
	if err != nil {
		return res, err
	}
	if !found {
		// Never started: the last committed conversation is the seed.
		return parent.Self().Seed, nil
	}
	return rt.Snapshot(), nil
}

func (s agentSchema) start(ctx context.Context, parent dagql.ObjectResult[*core.Agent], _ struct{}) (res dagql.Result[core.AgentID], _ error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return res, err
	}
	if _, err := agents.Start(ctx, parent); err != nil {
		return res, err
	}
	return agentSelfID(ctx, parent)
}

func (s agentSchema) send(ctx context.Context, parent dagql.ObjectResult[*core.Agent], args struct {
	Message string
}) (res dagql.Result[core.AgentMessageID], _ error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return res, err
	}
	// Signal-with-start plus delivery-evidence computation both live in the
	// registry's central enqueue path.
	msg, err := agents.Send(ctx, parent, args.Message)
	if err != nil {
		return res, err
	}
	// send is DoNotCache — every send enqueues a distinct message — and
	// DoNotCache results are detached in dagql: they have no addressable
	// ID, which would break the cancel-and-re-await contract across
	// requests. Pin the handle's identity by re-exec (design §9, the same
	// trick step() uses to materialize state as selectors): a real Select
	// through the message lookup field, on the agent receiver instance,
	// yields an instance whose ID is the honest, replayable chain
	// `…asAgent!message(id:"…")` — addressable from any request in the
	// session. That pinned ID is the result: send is imperative, so like
	// the other verbs it returns ID! rather than the object, forcing lazy
	// clients to execute the (unrepeatable) enqueue exactly once and
	// re-hydrate the handle from the ID — which replays the lookup, not
	// the send.
	srv, err := core.CurrentDagqlServer(ctx)
	if err != nil {
		return res, err
	}
	var pinned dagql.ObjectResult[*core.AgentMessage]
	if err := srv.Select(ctx, parent, &pinned, dagql.Selector{
		Field: "message",
		Args: []dagql.NamedInput{
			{
				Name:  "id",
				Value: dagql.NewString(msg.MessageID),
			},
		},
	}); err != nil {
		return res, err
	}
	pinnedID, err := pinned.ID()
	if err != nil {
		return res, fmt.Errorf("message ID: %w", err)
	}
	return dagql.NewResultForCurrentCall(ctx, dagql.NewID[*core.AgentMessage](pinnedID))
}

func (s agentSchema) message(ctx context.Context, parent dagql.ObjectResult[*core.Agent], args struct {
	ID string
}) (*core.AgentMessage, error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return nil, err
	}
	return agents.LookupMessage(ctx, parent, args.ID)
}

func (s agentSchema) interrupt(ctx context.Context, parent dagql.ObjectResult[*core.Agent], _ struct{}) (res dagql.Result[core.AgentID], _ error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return res, err
	}
	// Interrupting a never-started agent degenerates to pause, so create
	// the entry lazily (without starting the loop), like pause does.
	rt, err := agents.GetOrCreate(ctx, parent)
	if err != nil {
		return res, err
	}
	if err := rt.Interrupt(); err != nil {
		return res, err
	}
	return agentSelfID(ctx, parent)
}

func (s agentSchema) pause(ctx context.Context, parent dagql.ObjectResult[*core.Agent], _ struct{}) (res dagql.Result[core.AgentID], _ error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return res, err
	}
	// Pausing a never-started agent creates its entry lazily, paused: a
	// later start or send parks immediately, with mail queuing as QUEUED.
	rt, err := agents.GetOrCreate(ctx, parent)
	if err != nil {
		return res, err
	}
	if err := rt.Pause(); err != nil {
		return res, err
	}
	return agentSelfID(ctx, parent)
}

func (s agentSchema) resume(ctx context.Context, parent dagql.ObjectResult[*core.Agent], _ struct{}) (res dagql.Result[core.AgentID], _ error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return res, err
	}
	// Lazy entry for symmetry with pause: resuming a never-started,
	// never-paused agent is a documented no-op.
	rt, err := agents.GetOrCreate(ctx, parent)
	if err != nil {
		return res, err
	}
	if err := rt.Resume(ctx); err != nil {
		return res, err
	}
	return agentSelfID(ctx, parent)
}

func (s agentSchema) messageDelivery(ctx context.Context, msg *core.AgentMessage, _ struct{}) (core.AgentMessageDelivery, error) {
	return msg.Delivery, nil
}

func (s agentSchema) messageAwait(ctx context.Context, msg *core.AgentMessage, _ struct{}) (string, error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return "", err
	}
	return agents.AwaitMessage(ctx, msg)
}

func (s agentSchema) waitFor(ctx context.Context, parent dagql.ObjectResult[*core.Agent], args struct {
	State core.AgentState `default:"IDLE"`
}) (res dagql.Result[core.AgentID], _ error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return res, err
	}
	// Create the entry lazily (without starting the loop) so waiting on a
	// never-started agent blocks on future transitions instead of erroring.
	rt, err := agents.GetOrCreate(ctx, parent)
	if err != nil {
		return res, err
	}
	if err := rt.WaitFor(ctx, args.State); err != nil {
		return res, err
	}
	return agentSelfID(ctx, parent)
}

func (s agentSchema) stop(ctx context.Context, parent dagql.ObjectResult[*core.Agent], args struct {
	Kill bool `default:"false"`
}) (res dagql.Result[core.AgentID], _ error) {
	agents, err := agentRuntimes(ctx)
	if err != nil {
		return res, err
	}
	// Stopping a never-started agent still creates its entry, transitioned
	// straight to the tombstone: stop is terminal either way, and idempotent.
	rt, err := agents.GetOrCreate(ctx, parent)
	if err != nil {
		return res, err
	}
	if err := rt.Stop(ctx, args.Kill, nil); err != nil {
		return res, err
	}
	return agentSelfID(ctx, parent)
}
