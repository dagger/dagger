func TestGoBindingsMatchSource(t *testing.T) {
	check := func(t *testing.T, source string, more map[string]string) error {
		t.Helper()
		sources := map[string]string{"main.go": source}
		for name, contents := range more {
			sources[name] = contents
		}
		return goBindingsMatchSource(goBindingsTestGenerated, sources, goBindingsTestImport)
	}
	replace := func(t *testing.T, old, new string) string {
		t.Helper()
		require.Contains(t, goBindingsTestSource, old)
		return strings.Replace(goBindingsTestSource, old, new, 1)
	}

	t.Run("matching source", func(t *testing.T) {
		require.NoError(t, check(t, goBindingsTestSource, nil))
	})

	// Each of these modules doesn't compile: bindings that don't fit the source
	// must not be trusted.
	for _, tc := range []struct {
		name     string
		old, new string
		want     string
	}{
		{"function removed", "func (m *Test) Value() string { return \"value\" }\n", "", "Value"},
		{"constructor removed", "func New(greeting string) *Test { return &Test{Greeting: greeting} }\n", "", "New"},
		{"object removed", "type Sub struct{}\n", "", "Sub"},
		{"field removed", "\tSecret   string\n", "", "Secret"},
		{"enum member removed", "const ModeFast Mode = \"fast\"\n", "", "ModeFast"},
		{"enum removed", "type Mode string\n\nconst ModeFast Mode = \"fast\"\n", "", "Mode"},
		{"argument removed", "name string, times int,", "name string,", "too many arguments"},
		{"argument added", "name string, times int,", "name string, times int, extra bool,", "not enough arguments"},
		{"argument type changed", "name string, times int,", "name string, times string,", "times"},
		{"context argument changed", "ctx context.Context, name string", "ctx string, name string", "ctx"},
		{"interface argument changed", "duck Duck)", "duck string)", "toIface"},
		{"binding type changed", "file *dagger.File, duck", "file *dagger.Directory, duck", "file"},
		{"variadic argument changed", "Many(names ...string)", "Many(names []string)", "non-variadic"},
		{"field type changed", "\tSecret   string\n", "\tSecret   int\n", "Secret"},
		{"return count changed", "func (m *Test) Value() string", "func (m *Test) Value() (string, error)", "Value"},
		{"error return changed", "Lint(ctx context.Context) error { return nil }", "Lint(ctx context.Context) string { return \"\" }", "Lint"},
		{"void became an error", "func (m *Test) Quiet() {}", "func (m *Test) Quiet() error { return nil }", ""},
		{"interface gained a method", "Quack(ctx context.Context) (string, error)\n", "Quack(ctx context.Context) (string, error)\n\tWaddle()\n", "Waddle"},
		{"interface method changed", "Quack(ctx context.Context) (string, error)\n", "Quack(ctx context.Context) (int, error)\n", "Quack"},
		{"enum member type changed", "const ModeFast Mode = \"fast\"\n", "const ModeFast = 1\n", "ModeFast"},
		{"return type from a package that isn't there", "Lint(ctx context.Context) error { return nil }", "Lint(ctx context.Context) time.Duration { return 0 }", "signature of Lint"},
		{"argument type from a package that isn't there", "name string, times int,", "name string, times time.Duration,", "signature of Hello"},
		{"return type named after a type from a package that isn't there", "Lint(ctx context.Context) error { return nil }", "Lint(ctx context.Context) Delay { return 0 }\n\ntype Delay time.Duration", "signature of Lint"},
		{"return type a named pointer to a type from a package that isn't there", "Lint(ctx context.Context) error { return nil }", "Lint(ctx context.Context) Failure { return nil }\n\ntype Failure *os.PathError", "signature of Lint"},
		{"a recursive named type", "Lint(ctx context.Context) error { return nil }", "Lint(ctx context.Context) Chain { return nil }\n\ntype Chain []Chain", "Lint"},
		{"a method the generated code also declares", "func (m *Test) Quiet() {}\n", "func (m *Test) Quiet() {}\n\nfunc (t Test) MarshalJSON() ([]byte, error) { return nil, nil }\n", "MarshalJSON"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			err := check(t, replace(t, tc.old, tc.new), nil)
			if tc.name == "void became an error" {
				// A call that ignores a result compiles.
				require.NoError(t, err)
				return
			}
			require.ErrorContains(t, err, tc.want)
		})
	}

	// A stale module that still compiles has the API its bindings say: nothing
	// would call the new method, as nothing would in the binary.
	t.Run("new method not generated yet", func(t *testing.T) {
		require.NoError(t, check(t, goBindingsTestSource+"\nfunc (m *Test) Added() string { return \"\" }\n", nil))
	})

	// Declarations only: the build reports a broken body at the first call.
	t.Run("broken function body", func(t *testing.T) {
		require.NoError(t, check(t, replace(t, `return "value"`, `return undefinedSymbol()`), nil))
	})

	t.Run("declared in another file", func(t *testing.T) {
		source := replace(t, "func (m *Test) Value() string { return \"value\" }\n", "")
		require.NoError(t, check(t, source, map[string]string{
			"more.go": "package main\n\nfunc (m *Test) Value() string { return \"\" }\n",
		}))
	})

	t.Run("declared only in a file the build leaves out", func(t *testing.T) {
		source := replace(t, "func (m *Test) Value() string { return \"value\" }\n", "")
		err := check(t, source, map[string]string{
			"more_windows.go": "package main\n\nfunc (m *Test) Value() string { return \"\" }\n",
		})
		require.ErrorContains(t, err, "Value")
		err = check(t, source, map[string]string{
			"more.go": "//go:build ignore\n\npackage main\n\nfunc (m *Test) Value() string { return \"\" }\n",
		})
		require.ErrorContains(t, err, "Value")
	})

	// A build without cgo leaves this file out, and the method with it.
	t.Run("declared only in a file that imports C", func(t *testing.T) {
		source := replace(t, "func (m *Test) Value() string { return \"value\" }\n", "")
		err := check(t, source, map[string]string{
			"cgo.go": "package main\n\nimport \"C\"\n\nfunc (m *Test) Value() string { return \"\" }\n",
		})
		require.ErrorContains(t, err, "Value")
	})

	// The same on any engine: amd64's files, here on any architecture.
	t.Run("declared only for an architecture the check doesn't use", func(t *testing.T) {
		source := replace(t, "func (m *Test) Value() string { return \"value\" }\n", "")
		value := "package main\n\nfunc (m *Test) Value() string { return \"\" }\n"
		require.NoError(t, check(t, source, map[string]string{
			"amd64.go": "//go:build amd64.v1\n\n" + value,
			"arm64.go": "//go:build arm64\n\n" + value,
		}))
		require.ErrorContains(t, check(t, source, map[string]string{"value_arm64.go": value}), "Value")
	})

	// Spellings that differ but mean the same aren't mismatches.
	t.Run("a type alias", func(t *testing.T) {
		source := replace(t, "name string, times int,", "name Name, times int,") + "\ntype Name = string\n"
		require.NoError(t, check(t, source, nil))
	})
	t.Run("a different name for the bindings' import", func(t *testing.T) {
		source := replace(t, `"dagger/test/internal/dagger"`, `d "dagger/test/internal/dagger"`)
		source = strings.ReplaceAll(source, "dagger.File", "d.File")
		source = strings.ReplaceAll(source, "dagger.DaggerObject", "d.DaggerObject")
		require.NoError(t, check(t, source, nil))
	})
	t.Run("promoted from an embedded field", func(t *testing.T) {
		source := replace(t, "\tSecret   string\n", "\tHidden\n") + "\ntype Hidden struct{ Secret string }\n"
		require.NoError(t, check(t, source, nil))
	})
	t.Run("a third-party type in a private field", func(t *testing.T) {
		source := replace(t, "\tSecret   string\n", "\tSecret   string\n\tinternal thirdparty.Thing\n")
		source = strings.Replace(source, `"context"`, "\"context\"\n\n\t\"example.com/thirdparty\"", 1)
		require.NoError(t, check(t, source, nil))
	})

	t.Run("the bindings' import name rebound to another package", func(t *testing.T) {
		source := replace(t, `"dagger/test/internal/dagger"`, `dagger "os"`)
		source = strings.Replace(source, "dagger.DaggerObject\n", "", 1)
		require.ErrorContains(t, check(t, source, nil), "signature of Hello")
	})
}

func TestGoRegistrationExpr(t *testing.T) {
	replace := func(t *testing.T, old, new string) string {
		t.Helper()
		require.Contains(t, goBindingsTestGenerated, old)
		return strings.Replace(goBindingsTestGenerated, old, new, 1)
	}
	t.Run("generated shape", func(t *testing.T) {
		_, err := goRegistrationExpr(goBindingsTestGenerated)
		require.NoError(t, err)
	})
	for _, tc := range []struct {
		name string
		src  string
		want string
	}{
		{
			"the arm returns an error",
			replace(t, `WithObject(dag.TypeDef().WithObject("Test")), nil`, `WithObject(dag.TypeDef().WithObject("Test")), fmt.Errorf("no")`),
			"doesn't return a module and nil",
		},
		{
			"a statement before the switch",
			replace(t, "\t_ = inputArgs\n", "\t_ = inputArgs\n\tif parentName == \"\" {\n\t\treturn nil, nil\n\t}\n"),
			"invoke has 3 statements",
		},
		{
			"a statement in the arm",
			replace(t, "\t\treturn dag.Module().\n", "\t\tfmt.Println()\n\t\treturn dag.Module().\n"),
			"registration arm has 2 statements",
		},
		{
			"no registration arm",
			replace(t, "\tcase \"\":\n\t\treturn dag.Module().\n\t\t\tWithObject(dag.TypeDef().WithObject(\"Test\")), nil\n", ""),
			"no registration arm",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, err := goRegistrationExpr(tc.src)
			require.ErrorContains(t, err, tc.want)
		})
	}
}

// A call outside the table is refused before anything is evaluated.
func TestGoRegistrationReaderRefusesUnknownCalls(t *testing.T) {
	for _, src := range []string{
		`dag.Module().With(identity)`,
		`dag.Directory()`,
		`other.Module()`,
		`dag.Module().WithDescription(description)`,
		`dag.Module().WithDescription(strings.ToUpper("x"))`,
	} {
		t.Run(src, func(t *testing.T) {
			expr, err := parser.ParseExprFrom(token.NewFileSet(), "x.go", src, 0)
			require.NoError(t, err)
			_, err = goRegistrationReader{}.eval(context.Background(), expr)
			require.Error(t, err)
		})
	}
}

