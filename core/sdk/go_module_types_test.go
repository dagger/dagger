// Every committed module in the repository has bindings the generator wrote for
// its source, so each must pass the check, or it would build for nothing.
func TestGoBindingsMatchCommittedModules(t *testing.T) {
	readDir := func(dir string) (map[string]string, error) {
		entries, err := os.ReadDir(dir)
		if err != nil {
			return nil, err
		}
		files := map[string]string{}
		for _, entry := range entries {
			name := entry.Name()
			if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
				continue
			}
			contents, err := os.ReadFile(filepath.Join(dir, name))
			if err != nil {
				return nil, err
			}
			files[name] = string(contents)
		}
		return files, nil
	}
	checked := 0
	err := filepath.WalkDir("../integration/testdata", func(file string, entry fs.DirEntry, err error) error {
		if err != nil || entry.Name() != goSDKGeneratedFile || strings.Contains(file, "internal/dagger") {
			return err
		}
		dir := filepath.Dir(file)
		sources, err := readDir(dir)
		if err != nil {
			return err
		}
		generated := sources[goSDKGeneratedFile]
		if !strings.Contains(generated, "return dag.Module()") {
			return nil
		}
		delete(sources, goSDKGeneratedFile)
		checked++
		_, err = goRegistrationExpr(generated)
		require.NoError(t, err, dir)
		require.NoError(t, goBindingsMatchSource(generated, sources, func(importPath string) (map[string]string, bool, error) {
			rel, ok := goGeneratedPackageDir(importPath)
			if !ok {
				return nil, false, nil
			}
			files, err := readDir(filepath.Join(dir, rel))
			return files, err == nil, err
		}), dir)
		return nil
	})
	require.NoError(t, err)
	require.NotZero(t, checked)
}
