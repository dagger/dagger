// sdkCommandExamples are the golden examples of the high-level commands a
// user runs every day, `dagger check` and `dagger generate`, beyond a single
// failing check (sdkCheckCases): several checks at once, a collection's
// checks, listing, and generators that change files or don't. They run in the
// SDK fixtures' own workspaces, viztest/sdks/checks/<lang>.
func sdkCommandExamples() []Example {
	workspace := func(lang string) string { return "./viztest/sdks/checks/" + lang }
	var examples []Example
	for _, lang := range []string{"dang", "python"} {
		checks := []string{"check-pass", "check-fail-exec"}
		// Passing and failing checks in one run, as `dagger check` runs
		// them all: the report counts both, shows only the failure's
		// detail, and suggests rerunning only it.
		examples = append(examples, Example{
			Name:         "sdks-" + lang + "-checks-mixed",
			Golden:       "sdks/" + lang + "/checks-mixed",
			Module:       workspace(lang),
			Function:     checks[0],
			Args:         checks[1:],
			Check:        true,
			Fail:         true,
			NormalizeSDK: true,
			OutputTest: func(t *testctx.T, out string) {
				require.NotContains(t, out, "__check_", "the report must not name a check's run span")
			},
			DBTest: func(t *testctx.T, db *dagui.DB) {
				for _, name := range checks {
					spans := checkSpans(db, name)
					require.NotEmpty(t, spans, "the check %s must have a span", name)
					for _, span := range spans {
						require.Equal(t, name != "check-fail-exec", span.CheckPassed, "the check %s's result", name)
					}
				}
				assertCheckOriginIsExec(t, db, "check-fail-exec", failingExecCmd)
			},
		})
	}
	return append(examples,
		// A collection's checks: one summary for the collection, its items'
		// checks beneath it, and the failing item's own output and error.
		Example{
			Name:         "sdks-dang-check-collection",
			Golden:       "sdks/dang/check-collection",
			Module:       workspace("dang"),
			Function:     "cases/check",
			Check:        true,
			Fail:         true,
			NormalizeSDK: true,
			OutputTest: func(t *testctx.T, out string) {
				require.NotContains(t, out, "__check_", "the report must not name a check's run span")
			},
			DBTest:  assertCaseChecks,
			LogTest: assertLoggedOnCheckItem,
		},
		// A collection with no items runs nothing, but was selected: the
		// command says so, and passes.
		Example{
			Name:         "sdks-dang-check-empty-collection",
			Golden:       "sdks/dang/check-empty-collection",
			Module:       workspace("dang"),
			Function:     "no-cases/check",
			Check:        true,
			NormalizeSDK: true,
		},
		// The checks a workspace has, as `dagger check -l` lists them,
		// generators' staleness checks and collections among them.
		Example{
			Name:         "sdks-dang-check-list",
			Golden:       "sdks/dang/check-list",
			Module:       workspace("dang"),
			Args:         []string{"-l"},
			Check:        true,
			NormalizeSDK: true,
		},
		// A generator that writes a file, applied. The warm-up applies it
		// too, so it's undone before the run the golden records.
		//
		// BAD: the report says nothing of what it changed, and names the
		// generator dag://?name=generateFile, not the
		// dag://?generator=generate-file a staleness check suggests running.
		Example{
			Name:         "sdks-dang-generate-file",
			Golden:       "sdks/dang/generate-file",
			Module:       workspace("dang"),
			Function:     "generate-file",
			Generate:     true,
			NormalizeSDK: true,
			OutputTest: func(t *testctx.T, _ string) {
				content, err := os.ReadFile(filepath.Join(workspace("dang"), "generated.txt"))
				require.NoError(t, err, "the generator's change must be applied")
				require.Equal(t, "generated by viztest-dang\n", string(content))
			},
			Setup: func(t *testctx.T) {
				generated := filepath.Join(workspace("dang"), "generated.txt")
				os.Remove(generated)
				t.Cleanup(func() { os.Remove(generated) })
			},
			AfterWarmup: func(t *testctx.T) {
				generated := filepath.Join(workspace("dang"), "generated.txt")
				content, err := os.ReadFile(generated)
				require.NoError(t, err, "the generator must write its file where it runs")
				require.Equal(t, "generated by viztest-dang\n", string(content))
				require.NoError(t, os.Remove(generated))
			},
		},
		// A generator with nothing to change.
		Example{
			Name:         "sdks-dang-generate-nothing",
			Golden:       "sdks/dang/generate-nothing",
			Module:       workspace("dang"),
			Function:     "generate-nothing",
			Generate:     true,
			NormalizeSDK: true,
		},
	)
}

// caseCheck is the check of a CheckCases item, as the report names it.
const caseCheck = "cases/check"

// assertCaseChecks checks the check-collection example: the collection's
// summary check failed, with each item's check beneath it, only the "fail"
// item's failing, with its own error as its origin.
func assertCaseChecks(t *testctx.T, db *dagui.DB) {
	var groups, items, failed int
	for _, span := range db.Spans.Order {
		if span.CheckName == "" || span.IsRunning() {
			continue
		}
		if span.CheckCollectionGroup {
			groups++
			// The summary is named for the collection's check path.
			require.Equal(t, caseCheck, span.CheckName)
			require.False(t, span.CheckPassed, "a collection with a failing item fails")
			continue
		}
		item, _ := span.ExtraAttributes.Get(telemetryattrs.CheckCollectionItemAttr)
		if string(item) != "true" {
			continue
		}
		items++
		parent := span.ParentSpan
		for parent != nil && parent.CheckName == "" {
			parent = parent.ParentSpan
		}
		require.NotNil(t, parent, "the item %s must be under its collection's summary", span.CheckName)
		require.True(t, parent.CheckCollectionGroup, "the item %s must be under its collection's summary, not %s", span.CheckName, parent.CheckName)
		failing := strings.HasSuffix(span.CheckName, "=cases.fail")
		require.Equal(t, !failing, span.CheckPassed, "the item %s's result", span.CheckName)
		require.Equal(t, failing, span.IsFailed(), "the item %s's span", span.CheckName)
		if failing {
			failed++
			require.Empty(t, spanNames(span.ErrorOrigins.Spans()), "the item %s must be its error's origin", span.CheckName)
		}
	}
	require.NotZero(t, groups, "the collection must have a summary")
	require.Equal(t, 2, items, "each item must have a check")
	require.Equal(t, 1, failed, "only the fail item's check must fail")
}

// assertLoggedOnCheckItem checks that each item's check logs on its own span.
func assertLoggedOnCheckItem(t *testctx.T, db *dagui.DB, logs []sdklog.Record) {
	for _, name := range []string{"fail", "pass"} {
		var found int
		for _, rec := range logs {
			body, _ := dagui.LogBodyString(rec)
			if body != "dang case "+name+"\n" && body != "dang case "+name {
				continue
			}
			span := db.Spans.Map[db.LogTargetSpanID(rec)]
			require.NotNil(t, span, "the case %s's log must be on a span", name)
			item, _ := span.ExtraAttributes.Get(telemetryattrs.CheckCollectionItemAttr)
			require.Equal(t, "true", string(item), "the case %s's log must be on its check, not on %s", name, span.Name)
			found++
		}
		// The items' checks are cached per session, so both run again.
		require.NotZero(t, found, "the case %s must log", name)
	}
}
