#!/usr/bin/env node
// @ts-check
// Regenerates the thin per-type MDX stubs for the current docs and the rolling
// default version. Each stub just renders <ApiType name="..." />; all content
// comes from docs-graphql/schema.graphqls at build time via the
// dagger-api-reference plugin. The set of stubs is derived from the schema
// (every core type, with the featured ones first), so it stays complete as the
// schema grows:
//
//   node plugins/dagger-api-reference/generate-stubs.js
//
// docs-dev's References() pipeline invokes it after regenerating the schema.

const fs = require("fs");
const path = require("path");
const featured = require("./coreTypes.js");
const { orderedTypeNames } = require("./schema.js");

const schemaPath = path.resolve(
  __dirname,
  "../../docs-graphql/schema.graphqls"
);
const coreTypes = orderedTypeNames(schemaPath, featured);
const docsDir = path.resolve(__dirname, "../..");

// Keep in sync with typeSlug in src/components/api/data.ts.
function typeSlug(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();
}

const oldOutDir = path.join(docsDir, "current_docs/extending/types");

const banner =
  "{/* Generated by plugins/dagger-api-reference/generate-stubs.js — do not edit.\n" +
  "    Content comes from docs-graphql/schema.graphqls; edit the schema. */}";

function isGeneratedStub(file) {
  try {
    return fs
      .readFileSync(file, "utf8")
      .includes("Generated by plugins/dagger-api-reference/generate-stubs.js");
  } catch {
    return false;
  }
}

function removeGeneratedStubs(dir) {
  if (!fs.existsSync(dir)) return 0;
  let removed = 0;
  for (const f of fs.readdirSync(dir)) {
    if (!f.endsWith(".mdx")) continue;
    const file = path.join(dir, f);
    if (isGeneratedStub(file)) {
      fs.unlinkSync(file);
      removed++;
    }
  }
  return removed;
}

function stub(name, index, slugPrefix) {
  const slug = typeSlug(name);
  return `---
title: "${name}"
description: "${name} API reference, generated from the Dagger GraphQL schema."
sidebar_position: ${index + 2}
slug: /${slugPrefix}/${slug}
---

${banner}

import ApiType from "@site/src/components/api/ApiType";

## API reference

<ApiType name="${name}" />
`;
}

function syncStubs(outDir, slugPrefix) {
  fs.mkdirSync(outDir, { recursive: true });
  const removed = removeGeneratedStubs(outDir);
  let generated = 0;
  let skipped = 0;
  coreTypes.forEach((name, index) => {
    const file = path.join(outDir, `${typeSlug(name)}.mdx`);
    if (fs.existsSync(file)) {
      skipped++;
      return;
    }
    fs.writeFileSync(file, stub(name, index, slugPrefix));
    generated++;
  });
  return { generated, removed, skipped };
}

function findCategory(value, predicate) {
  if (Array.isArray(value)) {
    for (const item of value) {
      const found = findCategory(item, predicate);
      if (found) return found;
    }
    return undefined;
  }
  if (!value || typeof value !== "object") return undefined;
  if (value.type === "category" && predicate(value)) return value;
  for (const child of Object.values(value)) {
    const found = findCategory(child, predicate);
    if (found) return found;
  }
  return undefined;
}

function syncVersionedSidebar(sidebarPath, docPrefix) {
  const sidebar = JSON.parse(fs.readFileSync(sidebarPath, "utf8"));
  const reference = findCategory(
    sidebar,
    (category) => category.link?.id === `${docPrefix}/index`
  );
  if (!reference) {
    throw new Error(
      `could not find ${docPrefix}/index category in ${sidebarPath}`
    );
  }
  const other = reference.items.find(
    (item) => item && typeof item === "object" && item.label === "Other types"
  );
  if (!other) {
    throw new Error(`could not find Other types category in ${sidebarPath}`);
  }

  const present = new Set(coreTypes);
  const promoted = featured.filter((name) => present.has(name));
  const promotedSet = new Set(promoted);
  const docID = (name) => `${docPrefix}/${typeSlug(name)}`;
  const promotedItems = promoted.map((name) =>
    name === "Query"
      ? { type: "doc", id: docID(name), label: "Query (top-level)" }
      : docID(name)
  );
  other.items = coreTypes
    .filter((name) => !promotedSet.has(name))
    .sort((a, b) => a.localeCompare(b))
    .map(docID);
  reference.items = [...promotedItems, other, `${docPrefix}/all`];

  fs.writeFileSync(sidebarPath, `${JSON.stringify(sidebar, null, 2)}\n`);
}

function rollingVersionTarget() {
  const versionsPath = path.join(docsDir, "versions.json");
  if (!fs.existsSync(versionsPath)) return undefined;
  const versions = JSON.parse(fs.readFileSync(versionsPath, "utf8"));
  if (!versions.length) return undefined;

  // Docusaurus serves versions[0] at the site root. Its generated API pages
  // still render from the live schema, so their routes must roll forward with
  // the current stubs even though the surrounding docs are a snapshot.
  const version = versions[0];
  const versionDir = path.join(docsDir, `versioned_docs/version-${version}`);
  for (const docPrefix of [
    "reference/api",
    "api/reference",
    "extending/types",
  ]) {
    const allTypesPage = path.join(versionDir, docPrefix, "all.mdx");
    if (
      fs.existsSync(allTypesPage) &&
      fs.readFileSync(allTypesPage, "utf8").includes("<ApiTypeList")
    ) {
      return {
        version,
        outDir: path.join(versionDir, docPrefix),
        docPrefix,
        sidebarPath: path.join(
          docsDir,
          `versioned_sidebars/version-${version}-sidebars.json`
        ),
      };
    }
  }
  return undefined;
}

// Drop generated stubs from the old Types Reference location, then reconcile
// both sets of live-schema pages without touching hand-written type pages.
const removedOld = removeGeneratedStubs(oldOutDir);
const current = syncStubs(
  path.join(docsDir, "current_docs/reference/api"),
  "reference/api"
);

const rolling = rollingVersionTarget();
let rollingSummary = "no rolling live-schema reference found";
if (rolling) {
  const result = syncStubs(rolling.outDir, rolling.docPrefix);
  syncVersionedSidebar(rolling.sidebarPath, rolling.docPrefix);
  rollingSummary = `${rolling.version}: generated ${result.generated}, skipped ${result.skipped} hand-written pages, removed ${result.removed}`;
}

console.log(
  `Generated API reference stubs (current: generated ${current.generated}, skipped ${current.skipped} hand-written pages, removed ${removedOld} old and ${current.removed} stale; rolling ${rollingSummary}).`
);
