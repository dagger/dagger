//go:build ignore

package main

import (
	"fmt"
	"os"
	"strings"

	"golang.org/x/mod/semver"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	const versionFile = "internal/version/VERSION"
	contents, err := os.ReadFile(versionFile)
	if err != nil {
		return err
	}
	version := strings.TrimPrefix(strings.TrimSpace(string(contents)), "v")
	if !semver.IsValid("v" + version) {
		return fmt.Errorf("invalid version in %s: %q", versionFile, version)
	}
	return os.WriteFile("sdk/go/engineconn/version.gen.go", fmt.Appendf(nil, `// Code generated by go generate. DO NOT EDIT.

package engineconn

const CLIVersion = %q
`, version), 0o644)
}
