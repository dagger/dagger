package signoff

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"

	"github.com/BurntSushi/toml"
)

// DependencyObservation is the actual packaged coordinate decoded from one generated Cargo
// manifest after the installed Rust SDK has run. It matches the Rust facade's tagged observation
// without allowing the adapter to infer Git merely from the run plan.
type DependencyObservation struct {
	Source           string                   `json:"source"`
	Descriptor       RustDependencyDescriptor `json:"descriptor"`
	DescriptorDigest string                   `json:"descriptor_digest"`
}

// ObserveInstalledRustDependency admits only the exact two-key Cargo Git form generated by the
// packaged SDK. Registry, path, branch, tag, inherited, and ambiguous tables all fail closed.
func ObserveInstalledRustDependency(cargoManifest string) (DependencyObservation, error) {
	var document map[string]any
	if _, err := toml.Decode(cargoManifest, &document); err != nil {
		return DependencyObservation{}, fmt.Errorf("decode installed Rust Cargo manifest: %w", err)
	}
	dependencies, ok := document["dependencies"].(map[string]any)
	if !ok {
		return DependencyObservation{}, fmt.Errorf("installed Rust Cargo manifest has no dependency table")
	}
	raw, ok := dependencies["dagger-sdk"].(map[string]any)
	if !ok || len(raw) != 2 {
		return DependencyObservation{}, fmt.Errorf("installed dagger-sdk dependency is not exact immutable Git")
	}
	repository, repositoryOK := raw["git"].(string)
	revision, revisionOK := raw["rev"].(string)
	if !repositoryOK || !revisionOK || !isCommitSHA(revision) {
		return DependencyObservation{}, fmt.Errorf("installed dagger-sdk dependency is not exact immutable Git")
	}
	descriptor := RustDependencyDescriptor{
		Source: "git", Package: "dagger-sdk", URL: repository, Revision: revision,
	}
	canonical, err := json.Marshal(descriptor)
	if err != nil {
		return DependencyObservation{}, fmt.Errorf("encode installed Rust dependency descriptor: %w", err)
	}
	digest := sha256.Sum256(canonical)
	return DependencyObservation{
		Source: "git", Descriptor: descriptor, DescriptorDigest: fmt.Sprintf("sha256:%x", digest),
	}, nil
}
